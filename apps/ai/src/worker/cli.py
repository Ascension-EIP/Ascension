"""Command line entry point of the worker.

Without a sub-command the worker connects to its services and consumes jobs.
Each pipeline step registers its own sub-command in ``build_parser``.
"""

import argparse
import sys

from common.utils.logger import log


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="worker",
        description="Ascension AI worker. Without a sub-command, consume jobs from RabbitMQ.",
    )
    # Steps register here: sub.add_parser("<step>", help=...) (heavy imports stay in the handler).
    sub = parser.add_subparsers(dest="command", metavar="<step>")

    p = sub.add_parser("pose-skeleton", help="Video -> raw skeleton JSON.")
    p.add_argument("--video", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--render", help="Also write a video with the skeleton drawn on it.")
    p.set_defaults(run=_pose_skeleton)

    p = sub.add_parser("pose-filter", help="Raw JSON -> filtered JSON (gaps, smoothing, angles).")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--min-visibility", type=float, help="Default: 0.5")
    p.add_argument("--max-gap", type=int, help="Default: 5 frames")
    p.add_argument("--window", type=int, help="Default: 5 frames")
    p.set_defaults(run=_pose_filter)

    p = sub.add_parser("pose-metrics", help="Filtered JSON -> JSON with speeds and metrics.")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--bent-arm", type=float, help="Default: 0.8")
    p.set_defaults(run=_pose_metrics)

    p = sub.add_parser("pose-movements", help="Metrics JSON -> JSON with movements and pauses.")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--move-speed", type=float, help="Default: 0.8 torso lengths/s")
    p.add_argument("--stop-speed", type=float, help="Default: 0.4 torso lengths/s")
    p.add_argument("--merge-gap", type=float, help="Default: 150 ms")
    p.add_argument("--min-move", type=float, help="Default: 100 ms")
    p.add_argument("--min-pause", type=float, help="Default: 500 ms")
    p.set_defaults(run=_pose_movements)

    p = sub.add_parser("pose-detect", help="Video -> full analysis result JSON.")
    p.add_argument("--video", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--render", help="Also write a video with the skeleton drawn on it.")
    p.set_defaults(run=_pose_detect)

    p = sub.add_parser("pose-advice", help="Result JSON -> Hints JSON generated by the LLM.")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--dry-run", action="store_true", help="Write the prompt to --out; no network, no key.")
    p.add_argument("--model", help="Overrides LLM_MODEL.")
    p.add_argument("--base-url", help="Overrides LLM_BASE_URL.")
    p.set_defaults(run=_pose_advice)
    return parser


def _write(path: str, data: dict) -> None:
    """Validate against `AnalysisResult`, then write without null fields."""
    from pathlib import Path

    from shared.models import AnalysisResult

    Path(path).write_text(AnalysisResult.model_validate(data).model_dump_json(exclude_none=True))
    log.info("Wrote %s", path)


def _read(path: str) -> dict:
    import json
    from pathlib import Path

    return json.loads(Path(path).read_text())


def _kwargs(args: argparse.Namespace, **names: str) -> dict:
    """Map CLI options to function arguments, keeping function defaults when unset."""
    return {k: getattr(args, v) for k, v in names.items() if getattr(args, v) is not None}


def _pose_skeleton(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._1_pose_skeleton import PoseSkeleton

    _write(args.out, PoseSkeleton().process(args.video, args.render).result)


def _pose_filter(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._2_pose_filter import filter_frames

    kw = _kwargs(args, min_visibility="min_visibility", max_gap="max_gap", window="window")
    _write(args.out, filter_frames(_read(args.input), **kw))


def _pose_metrics(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._3_pose_metrics import compute_metrics

    kw = _kwargs(args, bent_arm_threshold="bent_arm")
    _write(args.out, compute_metrics(_read(args.input), **kw))


def _pose_movements(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._4_pose_movements import detect_movements

    kw = _kwargs(
        args,
        move_speed="move_speed",
        stop_speed="stop_speed",
        merge_gap_ms="merge_gap",
        min_move_ms="min_move",
        min_pause_ms="min_pause",
    )
    _write(args.out, detect_movements(_read(args.input), **kw))


def _pose_detect(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._0_pose_detect import detect_pose

    _write(args.out, detect_pose(args.video, args.render).model_dump())


def _pose_advice(args: argparse.Namespace) -> None:
    from pathlib import Path

    from services.llm import LLM
    from shared.models import AnalysisResult
    from worker._2_advice.pose_advice import PoseAdvice, build_prompt, summarize

    result = AnalysisResult.model_validate(_read(args.input)).model_dump(mode="json", exclude_none=True)
    if args.dry_run:
        Path(args.out).write_text(build_prompt(summarize(result)))
    else:
        llm = LLM().setup_config(args.base_url, args.model).connect()
        hints = PoseAdvice(llm, llm.config.model).process(result)
        Path(args.out).write_text(hints.model_dump_json(exclude_none=True))
    log.info("Wrote %s", args.out)


def consume() -> None:
    """Connect to the database, storage and broker, then block on consumption."""
    from worker.runtime import get_broker, get_db, get_storage

    get_db().connect()
    get_storage().connect()
    # start_consuming() blocks: it must be the last call.
    get_broker().setup_config().connect().setup_channel().start_consuming()


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    try:
        if args.command is None:
            consume()
        else:
            args.run(args)
    except KeyboardInterrupt:
        log.info("Interrupted, shutting down.")
    except Exception as e:  # noqa: BLE001
        log.error("Worker failed: %s", e)
        log.debug("Traceback", exc_info=True)
        sys.exit(1)
