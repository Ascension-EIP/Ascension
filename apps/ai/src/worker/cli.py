"""Command line entry point of the worker.

Without a sub-command the worker connects to its services and consumes jobs.
Each pipeline step registers its own sub-command in ``build_parser``.
"""

import argparse
import sys

from common.utils.logger import log


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="worker",
        description="Ascension AI worker. Without a sub-command, consume jobs from RabbitMQ.",
    )
    # Steps register here: sub.add_parser("<step>", help=...) (heavy imports stay in the handler).
    sub = parser.add_subparsers(dest="command", metavar="<step>")

    p = sub.add_parser("pose-skeleton", help="Video -> raw skeleton JSON.")
    p.add_argument("--video", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--render", help="Also write a video with the skeleton drawn on it.")
    p.set_defaults(run=_pose_skeleton)

    p = sub.add_parser("pose-filter", help="Raw JSON -> filtered JSON (gaps, smoothing, angles).")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--min-visibility", type=float, help="Default: 0.5")
    p.add_argument("--max-gap", type=int, help="Default: 5 frames")
    p.add_argument("--window", type=int, help="Default: 5 frames")
    p.set_defaults(run=_pose_filter)

    p = sub.add_parser("pose-metrics", help="Filtered JSON -> JSON with speeds and metrics.")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--bent-arm", type=float, help="Default: 0.8")
    p.set_defaults(run=_pose_metrics)

    p = sub.add_parser("pose-movements", help="Metrics JSON -> JSON with movements and pauses.")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--move-speed", type=float, help="Default: 0.8 torso lengths/s")
    p.add_argument("--stop-speed", type=float, help="Default: 0.4 torso lengths/s")
    p.add_argument("--merge-gap", type=float, help="Default: 150 ms")
    p.add_argument("--min-move", type=float, help="Default: 100 ms")
    p.add_argument("--min-pause", type=float, help="Default: 500 ms")
    p.set_defaults(run=_pose_movements)

    p = sub.add_parser("pose-detect", help="Video -> full analysis result JSON.")
    p.add_argument("--video", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--render", help="Also write a video with the skeleton drawn on it.")
    p.set_defaults(run=_pose_detect)

    p = sub.add_parser("pose-advice", help="Result JSON -> Hints JSON generated by the LLM.")
    p.add_argument("--input", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--dry-run", action="store_true", help="Write the prompt to --out; no network, no key.")
    p.add_argument("--model", help="Overrides LLM_MODEL.")
    p.add_argument("--base-url", help="Overrides LLM_BASE_URL.")
    p.set_defaults(run=_pose_advice)

    p = sub.add_parser("holds-detect", help="Route photo -> holds JSON (contour, type, colour).")
    p.add_argument("--image", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--render", help="Also write the photo with every hold drawn in its colour.")
    p.add_argument("--conf", type=float, help="Minimum confidence. Default: 0.10")
    p.add_argument("--model", help="ONNX model. Overrides HOLDS_MODEL_PATH.")
    p.set_defaults(run=_holds_detect)

    p = sub.add_parser("holds-colors-eval", help="Colour name accuracy on a labelled dataset (holds merge output).")
    p.add_argument("--dataset", required=True, help="e.g. training/holds/datasets/holds")
    p.add_argument("--splits", nargs="+", default=["val", "test"])
    p.set_defaults(run=_holds_colors_eval)

    p = sub.add_parser("ghost-depth", help="Route photo -> metric depth map in metres (.npy).")
    p.add_argument("--image", required=True)
    p.add_argument("--out", required=True, help="Depth map (H, W) float32 in metres, NaN where invalid.")
    p.add_argument("--render", help="Also write a coloured picture of the depth map.")
    p.set_defaults(run=_ghost_depth)

    p = sub.add_parser(
        "ghost-wall",
        help="Route photo (+ holds JSON) -> holds JSON with the wall plane (depth model, plane fit, homography).",
    )
    p.add_argument("--image", required=True)
    p.add_argument("--out", required=True, help="HoldDetectResult with `wall`; the marks of the holds are kept.")
    p.add_argument("--holds", help="Holds JSON (HoldDetectResult, holds may carry start_limbs/finish_limbs). Default: detect them.")
    p.add_argument("--gravity", type=float, nargs=3, metavar=("GX", "GY", "GZ"), help="Direction of the floor, camera frame.")
    p.set_defaults(run=_ghost_wall)

    p = sub.add_parser("ghost-beta", help="Holds JSON with a wall -> beta JSON (A* search: hold under each limb at each step).")
    p.add_argument("--input", required=True, help="Output of ghost-wall.")
    p.add_argument("--out", required=True)
    _climber_options(p)
    p.set_defaults(run=_ghost_beta)

    p = sub.add_parser("ghost-pose", help="Beta JSON + holds JSON with a wall -> GhostPath JSON (posture of each step, photo pixels).")
    p.add_argument("--input", required=True, help="Output of ghost-beta.")
    p.add_argument("--holds", required=True, help="Output of ghost-wall.")
    p.add_argument("--out", required=True)
    p.add_argument("--render", help="Also write the photo with the skeletons drawn on it (needs --image).")
    p.add_argument("--image")
    p.set_defaults(run=_ghost_pose)

    p = sub.add_parser("ghost", help="Route photo -> GhostPath JSON: ghost-wall, ghost-beta and ghost-pose in one go.")
    p.add_argument("--image", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--render", help="Also write the photo with the skeletons drawn on it.")
    p.add_argument("--holds", help="Holds JSON (HoldDetectResult, holds may carry start_limbs/finish_limbs). Default: detect them.")
    p.add_argument("--gravity", type=float, nargs=3, metavar=("GX", "GY", "GZ"), help="Direction of the floor, camera frame.")
    _climber_options(p)
    p.set_defaults(run=_ghost)

    p = sub.add_parser("depth-eval", help="Depth error on annotated wall photos (pairs of pixels and real distances).")
    p.add_argument("--dataset", required=True, help="Folder with the photos and annotations.json")
    p.set_defaults(run=_depth_eval)
    return parser


def _climber_options(p: argparse.ArgumentParser) -> None:
    p.add_argument("--morphology", help="GhostMorphology JSON (height, arm span, constraints). Overrides --height and --arm-span.")
    p.add_argument("--height", type=float, default=175.0, help="Height in cm. Default: 175")
    p.add_argument("--arm-span", type=float, default=178.0, help="Arm span in cm. Default: 178")
    p.add_argument("--preference", choices=["easy", "power", "technique"], default="easy", help="Default: easy")
    p.add_argument("--feet-free", action="store_true", help="Every usable hold of the photo can hold a foot.")
    p.add_argument("--selected", help="Ids of the holds of the route, comma separated (default: all; the id is the index in the file).")
    p.add_argument("--color", help="Colour name of the route: adds the holds whose color.name is this one (like routes.color) to --selected.")


def _write(path: str, data: dict) -> None:
    """Validate against `AnalysisResult`, then write without null fields."""
    from pathlib import Path

    from shared.models import AnalysisResult

    Path(path).write_text(AnalysisResult.model_validate(data).model_dump_json(exclude_none=True))
    log.info("Wrote %s", path)


def _read(path: str) -> dict:
    import json
    from pathlib import Path

    return json.loads(Path(path).read_text())


def _kwargs(args: argparse.Namespace, **names: str) -> dict:
    """Map CLI options to function arguments, keeping function defaults when unset."""
    return {k: getattr(args, v) for k, v in names.items() if getattr(args, v) is not None}


def _pose_skeleton(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._1_pose_skeleton import PoseSkeleton

    _write(args.out, PoseSkeleton().process(args.video, args.render).result)


def _pose_filter(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._2_pose_filter import filter_frames

    kw = _kwargs(args, min_visibility="min_visibility", max_gap="max_gap", window="window")
    _write(args.out, filter_frames(_read(args.input), **kw))


def _pose_metrics(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._3_pose_metrics import compute_metrics

    kw = _kwargs(args, bent_arm_threshold="bent_arm")
    _write(args.out, compute_metrics(_read(args.input), **kw))


def _pose_movements(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._4_pose_movements import detect_movements

    kw = _kwargs(
        args,
        move_speed="move_speed",
        stop_speed="stop_speed",
        merge_gap_ms="merge_gap",
        min_move_ms="min_move",
        min_pause_ms="min_pause",
    )
    _write(args.out, detect_movements(_read(args.input), **kw))


def _pose_detect(args: argparse.Namespace) -> None:
    from worker._1_mediapipe._0_pose_detect import detect_pose

    _write(args.out, detect_pose(args.video, args.render).model_dump())


def _pose_advice(args: argparse.Namespace) -> None:
    from pathlib import Path

    from services.llm import LLM
    from shared.models import AnalysisResult
    from worker._2_advice.pose_advice import PoseAdvice, build_prompt, summarize

    result = AnalysisResult.model_validate(_read(args.input)).model_dump(mode="json", exclude_none=True)
    if args.dry_run:
        Path(args.out).write_text(build_prompt(summarize(result)))
    else:
        llm = LLM().setup_config(args.base_url, args.model).connect()
        hints = PoseAdvice(llm, llm.config.model).process(result)
        Path(args.out).write_text(hints.model_dump_json(exclude_none=True))
    log.info("Wrote %s", args.out)


def _holds_detect(args: argparse.Namespace) -> None:
    from pathlib import Path

    from worker._3_holds._0_hold_detect import detect_holds
    from worker._3_holds._1_hold_segment import HoldSegmenter, model_path

    segmenter = HoldSegmenter(args.model or model_path())
    result = detect_holds(args.image, segmenter, args.render, **_kwargs(args, confidence="conf"))
    Path(args.out).write_text(result.model_dump_json(exclude_none=True))
    log.info("Wrote %s (%d holds)", args.out, len(result.holds))


def _holds_colors_eval(args: argparse.Namespace) -> None:
    from worker._3_holds.evaluate import evaluate_colors

    report = evaluate_colors(args.dataset, tuple(args.splits))
    print(f"accuracy {report['accuracy']:.3f} on {report['holds']} holds")
    for name, (accuracy, count) in report["per_color"].items():
        print(f"  {name:8s} {accuracy:.3f}  (n={count})")
    print("most frequent confusions (truth -> predicted):", report["confusions"])


def _ghost_depth(args: argparse.Namespace) -> None:
    from pathlib import Path

    import cv2
    import numpy as np

    from worker._3_holds._0_hold_detect import read_image
    from worker._4_ghost._1_depth import render_depth
    from worker.runtime import get_depth_estimator

    depth, focal = get_depth_estimator()(read_image(args.image))
    np.save(args.out, depth)
    if args.render:
        cv2.imwrite(args.render, render_depth(depth))
    valid = depth[np.isfinite(depth)]
    median = f"{np.median(valid):.2f}" if valid.size else "n/a"
    print(f"focal {focal:.1f} px, depth median {median} m, {valid.size / depth.size:.0%} valid pixels")
    log.info("Wrote %s", Path(args.out))


def _write_json(path: str, data: dict) -> None:
    import json
    from pathlib import Path

    Path(path).write_text(json.dumps(data))
    log.info("Wrote %s", path)


def _ghost_wall_data(args: argparse.Namespace) -> dict:
    """Holds JSON of ``--holds`` (or detected) plus the ``wall`` of the photo."""
    from pathlib import Path

    import numpy as np

    from common.utils.errors import PermanentError
    from shared.models import HoldDetectResult
    from worker._3_holds._0_hold_detect import detect_holds, read_image
    from worker._4_ghost._1_depth import depth_model_path
    from worker._4_ghost._4_ghost import estimate_photo_wall, validate_gravity
    from worker.runtime import get_depth_estimator, get_hold_segmenter

    validate_gravity(args.gravity)
    image = read_image(args.image)
    if args.holds:
        data = _read(args.holds)
        result = HoldDetectResult.model_validate(data)  # the marks of the holds stay in `data`
    else:
        result = detect_holds(args.image, get_hold_segmenter())
        data = result.model_dump(mode="json", exclude_none=True)
    if (result.image_width, result.image_height) != image.shape[:2][::-1]:
        raise PermanentError(
            f"holds are for a {result.image_width}x{result.image_height} photo, not {image.shape[1]}x{image.shape[0]}"
        )
    polygons = [np.array([(p.x, p.y) for p in hold.contour.points]) for hold in result.holds]
    model = Path(depth_model_path()).stem
    wall = estimate_photo_wall(image, polygons, get_depth_estimator(), args.gravity, model)
    log.info("Wall: %s, inliers %.0f%%", f"{wall.angle_deg:.1f} deg" if wall.angle_deg is not None else "angle unknown", 100 * wall.inlier_ratio)
    return data | {"wall": wall.model_dump(mode="json", exclude_none=True)}


def _wall_data(data: dict, source: str = "holds") -> tuple:
    """Wall and holds of a ghost-wall output (``data``, read from ``source``)."""
    from common.utils.errors import PermanentError
    from shared.models import HoldDetectResult
    from worker._4_ghost._4_ghost import photo_holds_from_dicts, validate_wall

    result = HoldDetectResult.model_validate(data)
    if result.wall is None:
        raise PermanentError(f"{source} has no wall: run ghost-wall first")
    validate_wall(result.wall)
    return result.wall, photo_holds_from_dicts(data["holds"])


def _selected_ids(args: argparse.Namespace, rows: list[dict]) -> list[str]:
    """Ids from --selected plus those of the holds of the --color colour (name compared in lower case)."""
    from common.utils.errors import PermanentError

    selected = [i for i in (args.selected or "").split(",") if i]
    if args.color:
        wanted = args.color.lower()
        names = {(row.get("color") or {}).get("name", "").lower() for row in rows} - {""}
        if wanted not in names:
            raise PermanentError(f"no hold of colour {args.color!r}; colours in the file: {', '.join(sorted(names)) or 'none'}")
        selected += [str(row.get("id", i)) for i, row in enumerate(rows) if (row.get("color") or {}).get("name", "").lower() == wanted]
    return selected


def _ghost_beta_data(args: argparse.Namespace, wall, holds, rows: list[dict]) -> dict:
    from shared.models import BetaPreference, GhostMorphology
    from worker._4_ghost._4_ghost import beta_to_json, find_ghost_beta

    if args.morphology:
        morphology = GhostMorphology.model_validate(_read(args.morphology))
    else:
        morphology = GhostMorphology(height_cm=args.height, arm_span_cm=args.arm_span)
    preference = BetaPreference(args.preference)
    selected = _selected_ids(args, rows)
    steps = find_ghost_beta(holds, wall, args.feet_free, selected, morphology, preference)
    log.info("Beta: %d steps", len(steps))
    return beta_to_json(steps, morphology.height_cm, preference, wall.angle_deg)


def _ghost_path(beta: dict, wall, holds, size: tuple[int, int]):
    from worker._4_ghost._4_ghost import beta_from_json, pose_steps

    steps, height = beta_from_json(beta)
    return pose_steps(steps, holds, wall, height, size)


def _ghost_wall(args: argparse.Namespace) -> None:
    _write_json(args.out, _ghost_wall_data(args))


def _ghost_beta(args: argparse.Namespace) -> None:
    data = _read(args.input)
    wall, holds = _wall_data(data, args.input)
    _write_json(args.out, _ghost_beta_data(args, wall, holds, data["holds"]))


def _write_ghost(args: argparse.Namespace, path, image_path: str | None) -> None:
    from pathlib import Path

    import cv2

    from worker._3_holds._0_hold_detect import read_image
    from worker._4_ghost._4_ghost import render_ghost

    Path(args.out).write_text(path.model_dump_json(exclude_none=True))
    log.info("Wrote %s (%d steps)", args.out, len(path.steps))
    if args.render:
        cv2.imwrite(args.render, render_ghost(read_image(image_path), path))


def _ghost_pose(args: argparse.Namespace) -> None:
    from common.utils.errors import PermanentError

    if args.render and not args.image:
        raise PermanentError("--render needs --image")
    data = _read(args.holds)
    wall, holds = _wall_data(data, args.holds)
    path = _ghost_path(_read(args.input), wall, holds, (data["image_width"], data["image_height"]))
    _write_ghost(args, path, args.image)


def _ghost(args: argparse.Namespace) -> None:
    data = _ghost_wall_data(args)
    wall, holds = _wall_data(data)
    path = _ghost_path(_ghost_beta_data(args, wall, holds, data["holds"]), wall, holds, (data["image_width"], data["image_height"]))
    _write_ghost(args, path, args.image)


def _depth_eval(args: argparse.Namespace) -> None:
    from worker._4_ghost._1_depth import evaluate_depth
    from worker.runtime import get_depth_estimator

    report = evaluate_depth(args.dataset, get_depth_estimator())
    for image in report["images"]:
        print(
            f"{image['image']}: mean {image['mean']:.1%} median {image['median']:.1%} "
            f"({len(image['errors'])} pairs, focal {image['focal_px']:.1f} px)"
        )
    print(
        f"all: {report['pairs']} pairs ({report['skipped']} skipped) "
        f"mean {report['mean']:.1%} median {report['median']:.1%}"
    )


def consume() -> None:
    """Connect to the database, storage and broker, then block on consumption."""
    from worker.runtime import get_broker, get_db, get_storage

    get_db().connect()
    get_storage().connect()
    # start_consuming() blocks: it must be the last call.
    get_broker().setup_config().connect().setup_channel().start_consuming()


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    try:
        if args.command is None:
            consume()
        else:
            args.run(args)
    except KeyboardInterrupt:
        log.info("Interrupted, shutting down.")
    except Exception as e:  # noqa: BLE001
        log.error("Worker failed: %s", e)
        log.debug("Traceback", exc_info=True)
        sys.exit(1)
