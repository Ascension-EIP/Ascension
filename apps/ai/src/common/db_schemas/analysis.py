"""Pydantic models mirroring the `analyses` table.

`AnalysisResult` describes exactly what `PoseSkeleton.process()` writes into
``mp_images_with_results``, so the worker output can be validated against the
database contract before it is stored:

    result = AnalysisResult.model_validate(pose_skeleton.mp_images_with_results)
    analysis = Analysis(video_id=..., result=result, status=JobStatus.COMPLETED)

`Hints` describes the structured advice generated by the external model (F09).
"""

from datetime import datetime
from enum import StrEnum
from typing import Self
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, model_validator


class AnalysisType(StrEnum):
    """`analysis_type` enum: which pipeline produced the analysis."""

    TWO_D = "2d"
    THREE_D = "3d"


class JobStatus(StrEnum):
    """`job_status` enum: lifecycle of an analysis job."""

    PENDING = "pending"
    PROCESSING = "processing"
    GENERATING_HINTS = "generating_hints"
    COMPLETED = "completed"
    FAILED = "failed"


class Visibility(StrEnum):
    """`visibility` enum: who is allowed to see the analysis."""

    PRIVATE = "private"
    FRIENDS = "friends"
    PUBLIC = "public"


class FocusArea(StrEnum):
    """`focus_area` enum: category of a hint."""

    TECHNIQUE = "technique"
    STRENGTH = "strength"
    ENDURANCE = "endurance"
    FLEXIBILITY = "flexibility"
    MENTAL = "mental"


class BodyZone(StrEnum):
    """`body_zone` enum: follows the MediaPipe segment layout."""

    HEAD = "head"
    NECK = "neck"
    TORSO = "torso"
    LOWER_BACK = "lower_back"
    LEFT_SHOULDER = "left_shoulder"
    RIGHT_SHOULDER = "right_shoulder"
    LEFT_UPPER_ARM = "left_upper_arm"
    RIGHT_UPPER_ARM = "right_upper_arm"
    LEFT_ELBOW = "left_elbow"
    RIGHT_ELBOW = "right_elbow"
    LEFT_FOREARM = "left_forearm"
    RIGHT_FOREARM = "right_forearm"
    LEFT_WRIST = "left_wrist"
    RIGHT_WRIST = "right_wrist"
    LEFT_HAND = "left_hand"
    RIGHT_HAND = "right_hand"
    LEFT_FINGERS = "left_fingers"
    RIGHT_FINGERS = "right_fingers"
    LEFT_HIP = "left_hip"
    RIGHT_HIP = "right_hip"
    LEFT_THIGH = "left_thigh"
    RIGHT_THIGH = "right_thigh"
    LEFT_KNEE = "left_knee"
    RIGHT_KNEE = "right_knee"
    LEFT_SHIN = "left_shin"
    RIGHT_SHIN = "right_shin"
    LEFT_ANKLE = "left_ankle"
    RIGHT_ANKLE = "right_ankle"
    LEFT_FOOT = "left_foot"
    RIGHT_FOOT = "right_foot"


class Landmark(BaseModel):
    """One MediaPipe pose landmark in normalized image coordinates."""

    model_config = ConfigDict(extra="forbid")

    x: float
    y: float
    z: float
    visibility: float


class Frame(BaseModel):
    """Pose detection output for a single video frame."""

    model_config = ConfigDict(extra="forbid")

    frame: int
    timestamp_ms: int
    pose_detected: bool
    #: Keyed by lowercase MediaPipe landmark name (e.g. ``left_shoulder``).
    landmarks: dict[str, Landmark] = Field(default_factory=dict)
    #: Keyed by joint name (see ``PoseSkeleton.JOINTS``), in degrees.
    angles: dict[str, float] = Field(default_factory=dict)


class AnalysisResult(BaseModel):
    """Payload stored in `analyses.result`, produced by `PoseSkeleton.process()`."""

    model_config = ConfigDict(extra="forbid")

    fps: float
    width: int
    height: int
    frames: list[Frame] = Field(default_factory=list)


class Hint(BaseModel):
    """One piece of advice returned by the external model.

    Extra keys are ignored, so a chatty model cannot break the ingestion.
    """

    category: FocusArea
    priority: int = Field(ge=1, le=5)
    title: str
    description: str
    frame_start: int | None = None
    frame_end: int | None = None
    body_zones: list[BodyZone] = Field(default_factory=list)


class Hints(BaseModel):
    """Payload stored in `analyses.hints`, generated by the external model (F09)."""

    summary: str
    items: list[Hint] = Field(default_factory=list)
    model: str
    generated_at: datetime


class Analysis(BaseModel):
    """Row of the `analyses` table.

    Mirrors the `chk_analyses_progress`, `chk_analyses_completed` and
    `chk_analyses_failed` CHECK constraints, so an invalid row fails here
    instead of at the PostgreSQL boundary.
    """

    model_config = ConfigDict(from_attributes=True)

    id: UUID | None = None
    video_id: UUID
    type: AnalysisType = AnalysisType.TWO_D
    status: JobStatus = JobStatus.PENDING
    progress: int = Field(default=0, ge=0, le=100)
    result: AnalysisResult | None = None
    hints: Hints | None = None
    error: str | None = None
    processing_time_ms: int | None = None
    started_at: datetime | None = None
    completed_at: datetime | None = None
    visibility: Visibility = Visibility.PRIVATE
    created_at: datetime | None = None
    updated_at: datetime | None = None

    @model_validator(mode="after")
    def check_status_consistency(self) -> Self:
        """Enforce `chk_analyses_completed` and `chk_analyses_failed`."""
        if self.status == JobStatus.COMPLETED and (
            self.result is None or self.completed_at is None
        ):
            raise ValueError(
                "a completed analysis requires both `result` and `completed_at`"
            )
        if self.status == JobStatus.FAILED and self.error is None:
            raise ValueError("a failed analysis requires `error`")
        return self
