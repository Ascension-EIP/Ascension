import 'package:equatable/equatable.dart';

/// Single landmark point extracted by MediaPipe Pose (normalized coordinates [0.0 - 1.0]).
class PoseLandmarkPoint extends Equatable {
  const PoseLandmarkPoint({
    required this.x,
    required this.y,
    this.z = 0.0,
    this.visibility = 1.0,
  });

  final double x;
  final double y;
  final double z;
  final double visibility;

  @override
  List<Object?> get props => [x, y, z, visibility];
}

/// Sided values (left and right measurements).
class SidesData extends Equatable {
  const SidesData({this.left, this.right});

  final double? left;
  final double? right;

  @override
  List<Object?> get props => [left, right];
}

/// Single video frame pose analysis entry.
class FramePose extends Equatable {
  const FramePose({
    required this.frame,
    required this.timestampMs,
    required this.poseDetected,
    required this.landmarks,
    this.angles = const {},
    this.armExtension,
    this.speeds,
  });

  final int frame;
  final int timestampMs;
  final bool poseDetected;
  final Map<String, PoseLandmarkPoint> landmarks;
  final Map<String, double> angles;
  final SidesData? armExtension;
  final Map<String, double>? speeds;

  @override
  List<Object?> get props => [
    frame,
    timestampMs,
    poseDetected,
    landmarks,
    angles,
    armExtension,
    speeds,
  ];
}

/// Aggregate biomechanical metrics computed over the full climb.
class AnalysisMetrics extends Equatable {
  const AnalysisMetrics({
    required this.durationMs,
    required this.poseDetectionRate,
    this.avgArmExtension,
    this.bentArmRatio,
    this.avgSpeed,
  });

  final int durationMs;
  final double poseDetectionRate;
  final SidesData? avgArmExtension;
  final SidesData? bentArmRatio;
  final Map<String, double>? avgSpeed;

  @override
  List<Object?> get props => [
    durationMs,
    poseDetectionRate,
    avgArmExtension,
    bentArmRatio,
    avgSpeed,
  ];
}

/// Specific limb movement segment detected during ascent.
class AnalysisMovement extends Equatable {
  const AnalysisMovement({
    required this.limb,
    required this.startFrame,
    required this.endFrame,
    required this.startMs,
    required this.endMs,
  });

  final String limb;
  final int startFrame;
  final int endFrame;
  final int startMs;
  final int endMs;

  int get durationMs => endMs - startMs;

  @override
  List<Object?> get props => [limb, startFrame, endFrame, startMs, endMs];
}

/// Detected resting pause interval during the ascent.
class AnalysisPause extends Equatable {
  const AnalysisPause({
    required this.startFrame,
    required this.endFrame,
    required this.startMs,
    required this.endMs,
  });

  final int startFrame;
  final int endFrame;
  final int startMs;
  final int endMs;

  int get durationMs => endMs - startMs;

  @override
  List<Object?> get props => [startFrame, endFrame, startMs, endMs];
}

