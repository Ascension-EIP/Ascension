/// Complete output result for a 2D pose analysis run.
class PoseAnalysisResult extends Equatable {
  const PoseAnalysisResult({
    required this.fps,
    required this.width,
    required this.height,
    required this.frames,
    this.metrics,
    this.movements = const [],
    this.pauses = const [],
    this.advice,
  });

  final double fps;
  final int width;
  final int height;
  final List<FramePose> frames;
  final AnalysisMetrics? metrics;
  final List<AnalysisMovement> movements;
  final List<AnalysisPause> pauses;
  final AnalysisAdvice? advice;

  /// Retrieves the nearest frame pose for a given playback timestamp in milliseconds.
  FramePose? getFrameAtTimestamp(int timestampMs) {
    if (frames.isEmpty) return null;
    if (timestampMs <= frames.first.timestampMs) return frames.first;
    if (timestampMs >= frames.last.timestampMs) return frames.last;

    int low = 0;
    int high = frames.length - 1;

    while (low <= high) {
      final mid = (low + high) ~/ 2;
      final midTime = frames[mid].timestampMs;

      if (midTime == timestampMs) {
        return frames[mid];
      } else if (midTime < timestampMs) {
        low = mid + 1;
      } else {
        high = mid - 1;
      }
    }

    // Return the closest of the two bounding frames
    if (low >= frames.length) return frames.last;
    if (high < 0) return frames.first;

    final diffLow = (frames[low].timestampMs - timestampMs).abs();
    final diffHigh = (frames[high].timestampMs - timestampMs).abs();

    return diffLow < diffHigh ? frames[low] : frames[high];
  }

  @override
  List<Object?> get props => [
    fps,
    width,
    height,
    frames,
    metrics,
    movements,
    pauses,
    advice,
  ];
}

